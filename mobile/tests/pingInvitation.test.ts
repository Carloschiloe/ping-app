import { describe, expect, it } from 'vitest';
import { PING_APP_INVITE_URL, PING_PUBLIC_INVITE_URL, normalizePingInviteUrl } from '../src/utils/pingInvitation';

describe('Ping invitations', () => {
    it('never shares an Expo Go runtime URL', () => {
        expect(normalizePingInviteUrl('exp://192.168.1.10:8081')).toBe(PING_APP_INVITE_URL);
        expect(normalizePingInviteUrl('exps://example.invalid')).toBe(PING_APP_INVITE_URL);
    });

    it('preserves the installed Ping URL generated by the standalone runtime', () => {
        expect(normalizePingInviteUrl('ping:///invite')).toBe('ping:///invite');
    });

    it('uses a clickable HTTPS production invitation URL', () => {
        expect(PING_PUBLIC_INVITE_URL).toBe('https://ping-app-con3.onrender.com/invite');
        expect(PING_PUBLIC_INVITE_URL).toMatch(/^https:\/\//);
    });
});
